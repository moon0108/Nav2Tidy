#!/usr/bin/env python3
"""Render nav.scene.WALLS into the two files Gazebo and Nav2 each need.

nav/scene.py owns every wall coordinate -- its docstring forbids a second source
-- so this only renders. Re-run after editing scene.py:

    PYTHONPATH=/home/moon/tidybot2 python3 scripts/gen_world.py

The self-check is the point: every pair in scene.SCENARIOS, plus the two the
MuJoCo benchmark already uses, must stay A*-reachable at PLAN_CLEARANCE. A layout
that pinches a gap below it fails here instead of stranding an episode later.
"""

from pathlib import Path
from xml.dom import minidom

import yaml

import numpy as np

from nav import scene
from nav.astar import astar
from nav.grid import is_free, plan_grid, static_grid

PKG = Path(__file__).resolve().parent.parent

# Fortress. Harmonic renames every one of these to gz-sim-*; do not mix the two.
_WORLD_HEAD = """<?xml version="1.0"?>
<!-- GENERATED by scripts/gen_world.py from nav/scene.py; do not edit by hand. -->
<sdf version="1.8">
  <world name="tidy">
    <!-- Gazebo's default. /clock comes out at exactly 1/max_step_size with no
         duplicates and no reordering; measured 10001 messages, 10001 unique
         stamps, 0 non-monotonic over 10 s, RTF 1.00 with the full Nav2 stack up.
         The "Detected jump back in time" storm that looked like a clock problem
         was several stale parameter_bridge processes publishing /clock at once
         after an incomplete kill; scripts/stop.sh is the fix for that, not a
         slower step. Raise this to 0.005 only if stage 4 measures bus
         saturation - it costs nothing here. -->
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system"
            name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system"
            name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system"
            name="ignition::gazebo::systems::SceneBroadcaster"/>
    <!-- gpu_lidar renders nothing without this one. -->
    <plugin filename="ignition-gazebo-sensors-system"
            name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <surface><friction><ode><mu>0</mu><mu2>0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material>
            <ambient>0.35 0.38 0.40 1</ambient>
            <diffuse>0.55 0.58 0.60 1</diffuse>
          </material>
        </visual>
      </link>
    </model>

    <model name="walls">
      <static>true</static>
      <link name="link">
"""

_WORLD_TAIL = """      </link>
    </model>
  </world>
</sdf>
"""


def _box_sdf(i, box):
    xmin, ymin, xmax, ymax = box
    cx, cy = (xmin + xmax) / 2, (ymin + ymax) / 2
    sx, sy, sz = xmax - xmin, ymax - ymin, scene.WALL_H
    return (
        f'        <collision name="c{i}">\n'
        f'          <pose>{cx:.4f} {cy:.4f} {sz / 2:.4f} 0 0 0</pose>\n'
        f'          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>\n'
        # A powered-caster base slides along a wall, it does not grab it. DART
        # combines the two surfaces with min(), so zero here is enough - and it
        # has to be here: sdformat's URDF parser silently drops <gazebo><mu1>.
        f'          <surface><friction><ode><mu>0</mu><mu2>0</mu2></ode></friction></surface>\n'
        f'        </collision>\n'
        f'        <visual name="v{i}">\n'
        f'          <pose>{cx:.4f} {cy:.4f} {sz / 2:.4f} 0 0 0</pose>\n'
        f'          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>\n'
        f'          <material>\n'
        f'            <ambient>0.35 0.35 0.38 1</ambient>\n'
        f'            <diffuse>0.55 0.55 0.60 1</diffuse>\n'
        f'          </material>\n'
        f'        </visual>\n'
    )


def write_sdf(path):
    path.write_text(_WORLD_HEAD
                    + ''.join(_box_sdf(i, b) for i, b in enumerate(scene.WALLS))
                    + _WORLD_TAIL)
    return path


def write_pgm(path, occ):
    """Nav2 map image. PGM row 0 is max-y, Grid.occ row 0 is min-y -- hence [::-1].

    254/0 rather than 255/0: map_server's trinary mode wants free strictly below
    free_thresh * 255 = 50 after the 255-p inversion, and 254 is the Nav2 idiom.
    """
    img = np.where(occ[::-1], 0, 254).astype(np.uint8)
    h, w = img.shape
    path.write_bytes(b'P5\n' + f'{w} {h}\n255\n'.encode() + img.tobytes())
    return path


def write_map_yaml(path, image, res, origin):
    path.write_text(
        f'image: {image}\n'
        'mode: trinary\n'
        f'resolution: {res}\n'
        f'origin: [{origin[0]}, {origin[1]}, 0.0]\n'
        'negate: 0\n'
        'occupied_thresh: 0.65\n'
        'free_thresh: 0.196\n')
    return path


def check_params(path):
    """nav2_params.yaml repeats numbers owned by nav/scene.py and MPPIConfig.

    Nav2 yaml cannot import python, so the numbers are typed twice; if the two
    copies drift the two planners are quietly driving different robots and every
    stage 4 comparison is void. Cheaper to assert than to explain later.
    """
    from nav.mppi import MPPIConfig

    p = yaml.safe_load(path.read_text())
    cfg = MPPIConfig()

    for ns in ('local_costmap', 'global_costmap'):
        got = p[ns][ns]['ros__parameters']['robot_radius']
        assert got == scene.ROBOT_RADIUS, \
            f'{ns}.robot_radius {got} != scene.ROBOT_RADIUS {scene.ROBOT_RADIUS}'

    fp = p['controller_server']['ros__parameters']['FollowPath']
    for key, want in zip(('vx_max', 'vy_max', 'wz_max'), cfg.v_max):
        assert fp[key] == want, f'FollowPath.{key} {fp[key]} != MPPIConfig.v_max {want}'

    # MPPIController throws on configure if the control period exceeds model_dt.
    period = 1.0 / p['controller_server']['ros__parameters']['controller_frequency']
    assert fp['model_dt'] >= period, \
        f"model_dt {fp['model_dt']} < control period {period:.5f}; MPPI will refuse to configure"

    # Matched horizon: the U trap turns on whether a planner can see past it.
    horizon = fp['time_steps'] * fp['model_dt']
    want = cfg.T * cfg.dt
    assert abs(horizon - want) < 0.05, f'MPPI horizon {horizon:.2f} s != MPPIConfig {want:.2f} s'

    # ObstaclesCritic rebuilds distance from cost using these two; against a
    # costmap inflated differently it scores a field that does not exist.
    infl = p['local_costmap']['local_costmap']['ros__parameters']['inflation_layer']
    for key in ('inflation_radius', 'cost_scaling_factor'):
        assert fp['ObstaclesCritic'][key] == infl[key], \
            f"ObstaclesCritic.{key} {fp['ObstaclesCritic'][key]} != costmap {infl[key]}"

    # Stage 3 reads MPPIConfig directly, so only the numbers the yaml restates
    # can drift: the solve rate against dt, and the goal line against Nav2's.
    mc = p['mppi_controller']['ros__parameters']
    assert abs(mc['solve_frequency'] - 1.0 / cfg.dt) < 1e-9, \
        f"solve_frequency {mc['solve_frequency']} != 1/MPPIConfig.dt {1 / cfg.dt}"
    gc = p['controller_server']['ros__parameters']['general_goal_checker']
    for key in ('xy_goal_tolerance', 'yaw_goal_tolerance'):
        assert mc[key] == gc[key], \
            f'mppi_controller.{key} {mc[key]} != general_goal_checker {gc[key]}; ' \
            'the two planners would be judged against different goal lines'

    print(f'  nav2_params.yaml agrees: r={scene.ROBOT_RADIUS}, '
          f'v_max={tuple(cfg.v_max)}, horizon={horizon:.2f} s, '
          f'solve {mc["solve_frequency"]} Hz, goal {gc["xy_goal_tolerance"]} m')


def check(*paths):
    """A* feasibility of every start/goal pair, plus XML well-formedness.

    XML comments may not contain '--', and both parsers reject the file outright
    when one does; Gazebo's failure mode for that is an empty world, not an error.
    """
    for p in paths:
        minidom.parse(str(p))

    pg = plan_grid()
    pairs = {k: (v[0][:2], v[1]) for k, v in scene.SCENARIOS.items()}
    # The MuJoCo side keeps running on this same geometry; adding walls must not
    # strand either of the pairs it already uses.
    pairs['legacy:default'] = ((0.0, 0.0), (8.0, 8.0))
    pairs['legacy:crowd'] = (scene.CROWD_START[:2], scene.CROWD_GOAL)

    for name, (s, g) in pairs.items():
        for label, pt in (('start', s), ('goal', g)):
            assert is_free(pg, pt, scene.PLAN_CLEARANCE), \
                f'{name}: {label} {tuple(pt)} is within {scene.PLAN_CLEARANCE} m of a wall'
        path = astar(pg, s, g, clearance=scene.PLAN_CLEARANCE)
        assert path is not None, f'{name}: no A* path {tuple(s)} -> {tuple(g)}'
        length = np.linalg.norm(np.diff(path, axis=0), axis=1).sum()
        print(f'  {name:16s} {tuple(s)} -> {tuple(g)}  {len(path):3d} wp, {length:5.2f} m')


def main():
    sdf = write_sdf(PKG / 'worlds' / 'tidy.sdf')
    g = static_grid()                     # GRID_RES = 0.05, the Nav2 map resolution
    pgm = write_pgm(PKG / 'maps' / 'tidy.pgm', g.occ)
    yml = write_map_yaml(PKG / 'maps' / 'tidy.yaml', 'tidy.pgm',
                         scene.GRID_RES, scene.GRID_ORIGIN)
    print(f'{len(scene.WALLS)} boxes -> {sdf}')
    print(f'{g.occ.shape} grid -> {pgm}, {yml}')
    check(sdf, PKG / 'urdf' / 'tidybot.urdf')
    check_params(PKG / 'config' / 'nav2_params.yaml')
    print('all scenarios reachable')


if __name__ == '__main__':
    main()
